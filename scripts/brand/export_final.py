"""Copy the final Ledger logo set to concepts/ledger/logo-final/ for the portal and admin repos.

    python scripts/brand/make_logo.py && python scripts/brand/make_icons.py && python scripts/brand/export_final.py
"""
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC_SVG = ROOT / "src" / "assets" / "brand"
KIT = ROOT / "brand" / "logo"
OUT = ROOT / "concepts" / "ledger" / "logo-final"

FILES = {
    "svg": sorted(p.name for p in SRC_SVG.glob("*.svg")),
    "png": ["icon-192.png", "icon-512.png"],
    "kit": sorted(p.name for p in KIT.glob("*.png")),
}

README = """# Drawbridge logo, final set (Ledger, type-design pass Oct 18, 2026)

Generated by `drawbridge-website/scripts/brand/make_logo.py` (letters: `ledger_type.py`) and `make_icons.py`.
Every letter is an outline: no fonts are needed. Copy these files; don't redraw or retype them.

| File | Use |
|---|---|
| `drawbridge-lockup.svg` | Primary: mark, wordmark, blue rule, "A MOATiT Service". On white. Minimum 150 px wide. |
| `drawbridge-lockup-reverse.svg` | The same on MOATiT ink (#222236) or other dark grounds. |
| `drawbridge-lockup-mono-indigo.svg` / `-mono-white.svg` | One colour (ink or white): fax cover sheets, embossing, one-colour print. |
| `drawbridge-lockup-stacked.svg` / `-stacked-reverse.svg` | Square-ish spaces: sign-in cards, social avatars, title slides. |
| `drawbridge-wordmark.svg` / `-reverse.svg` | The wordmark alone, where the mark already appears nearby. |
| `drawbridge-mark.svg` / `-reverse.svg` / `-mono.svg` | The mark alone (app chrome, small spaces). |
| `favicon.svg` | Browser icon, drawn on a 16 px grid: crisp at 16, 32 and 48 px. |
| `favicon.ico` | 16, 32 and 48 px, each rendered from `favicon.svg`. |
| `favicon-16/32/48/64.png` | The favicon as PNG at those exact sizes. |
| `drawbridge-app-icon.svg`, `icon-192.png`, `icon-512.png`, `apple-touch-icon.png` | Home-screen and app icons: the full mark on a padded white tile. |
| `drawbridge-*@4x.png` | Raster lockups for documents and email signatures. |

Colours: MOATiT navy #3E3E84 (post), MOATiT blue #29AAE1 (outer ring, rule), MOATiT gold #C68010 (inner ring;
#F5A623 on dark), ink #222236 (wordmark), slate #5A5C78 (endorsement). Write the name "Drawbridge, A MOATiT Service".
"""


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    for name in FILES["svg"]:
        shutil.copy2(SRC_SVG / name, OUT / name)
    for name in FILES["png"]:
        shutil.copy2(SRC_SVG / name, OUT / name)
    for name in FILES["kit"]:
        shutil.copy2(KIT / name, OUT / name)
    shutil.copy2(ROOT / "src" / "static" / "favicon.ico", OUT / "favicon.ico")
    shutil.copy2(ROOT / "src" / "static" / "apple-touch-icon.png", OUT / "apple-touch-icon.png")
    (OUT / "README.md").write_text(README, encoding="utf-8")
    print(f"{len(list(OUT.iterdir()))} files in {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
